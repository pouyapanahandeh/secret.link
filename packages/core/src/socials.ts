/**
 * Infer the social platform from a URL's hostname.
 * Falls back to "website" for unrecognized but valid URLs, and "" for empty/invalid input.
 */
export function detectPlatform(url: string): string {
  const trimmed = url.trim();
  if (!trimmed) return "";

  let host: string;
  try {
    const withProtocol = /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
    host = new URL(withProtocol).hostname.toLowerCase().replace(/^www\./, "");
  } catch {
    return "website";
  }

  const map: Record<string, string> = {
    "instagram.com": "instagram",
    "instagr.am": "instagram",
    "twitter.com": "twitter",
    "x.com": "twitter",
    "tiktok.com": "tiktok",
    "youtube.com": "youtube",
    "youtu.be": "youtube",
    "github.com": "github",
    "linkedin.com": "linkedin",
    "snapchat.com": "snapchat",
    "t.me": "telegram",
    "telegram.me": "telegram",
    "telegram.org": "telegram",
    "facebook.com": "facebook",
    "fb.com": "facebook",
    "whatsapp.com": "whatsapp",
    "wa.me": "whatsapp",
    "twitch.tv": "twitch",
    "discord.com": "discord",
    "discord.gg": "discord",
    "onlyfans.com": "onlyfans",
    "fansly.com": "fansly",
    "patreon.com": "patreon",
  };

  if (map[host]) return map[host]!;

  for (const domain of Object.keys(map)) {
    if (host === domain || host.endsWith(`.${domain}`)) return map[domain]!;
  }

  return "website";
}
